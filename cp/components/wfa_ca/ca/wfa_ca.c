{
    int nfds;
    // struct sockaddr_in servAddr;
    // unsigned short servPort;
    unsigned short myport = 9000;
    // char *servIP = NULL, *tstr = NULL;
    // int bytesRcvd; // Unused variable
    fd_set sockSet;
    int i, isFound = 0, nbytes = 0, tag, slen; // Unused variable , ret_status
    WORD xcCmdTag;
    int cmdLen = WFA_BUFF_1K, cmdLen1 = WFA_BUFF_1K ;
    int maxfdn1;
    char *pcmdStr = NULL;
    int respLen;
    tgThrData_t tdata[WFA_THREADS_NUM];

    for (i = 0; i < WFA_MAX_TRAFFIC_STREAMS; i++)
        tgSockfds[i] = -1;
    memset(gStreams, 0, sizeof(struct _tg_stream));
    memset(wmm_thr, 0, sizeof(wmm_thr));
    memset(tdata, 0, sizeof(tdata));
    wmm_fc_init();

#ifdef __LINUX__
    pthread_attr_t ptAttr;
    int ptPolicy;
    struct sched_param ptSchedParam;
#endif

    DPRINT_IN_FUNC();

    DPRINT_CONTENT("\r\n###########################################################\r\n");
    DPRINT_CONTENT("| -->>> Parsing DUT configuration file ...                |\r\n");
    DPRINT_CONTENT("###########################################################\r\n");
    if (wfa_dut_param_get_default() != WFA_SUCCESS) {
        DPRINT_ERR("Failed to get DUT parameters\r\n");
        return;
    }

    wSLEEP(1);

    DPRINT_BOX("Perform basic configuration ...");

    // @RW: Start
    trafficBuf = (BYTE *) malloc(MAX_UDP_LEN + 1); /* alloc a traffic buffer */
    if (trafficBuf == NULL) {
        DPRINT_ERR("Failed to malloc traffic buffer\r\n");
        return;
    }

    adj_latency = wfa_estimate_timer_latency() + 4000; /* four more mini */

    if (adj_latency > 500000) {
        printf("****************** WARNING  **********************\n");
        printf("!!!THE SLEEP TIMER LATENCY IS TOO HIGH!!!!!!!!!!!!\n");
        printf("**************************************************\n");

        /* Just set it to  500 mini seconds */
        adj_latency = 500000;
    }
    printf("adj_latency:%d\n", adj_latency);
    rtos_init_oneshot_timer(&wfa_tg_timer, 1000, tmout_stop_send, &wfa_tg_timer, NULL);

#ifdef __LINUX__
    pthread_attr_init(&ptAttr);

    ptSchedParam.sched_priority = 10;
    pthread_attr_setschedparam(&ptAttr, &ptSchedParam);
    pthread_attr_getschedpolicy(&ptAttr, &ptPolicy);
    pthread_attr_setschedpolicy(&ptAttr, SCHED_RR);
    pthread_attr_getschedpolicy(&ptAttr, &ptPolicy);
#endif

    /*
     * Create multiple threads for WMM Stream processing.
     */
    for (i = 0; i < WFA_THREADS_NUM; i++) {
        tdata[i].tid = i;
#ifdef __LINUX__
        pthread_mutex_init(&wmm_thr[i].thr_flag_mutex, NULL);
        pthread_cond_init(&wmm_thr[i].thr_flag_cond, NULL);
        wmm_thr[i].thr_id = pthread_create(&wmm_thr[i].thr, &ptAttr, wfa_wmm_thread, &tdata[i]);
#else
        rtos_init_semaphore(&wmm_thr[i].thr_flag_mutex, 1);
#ifdef CONFIG_FREERTOS_SMP
        rtos_create_thread_with_affinity(&wmm_thr[i].thr, -1, TG_APPLICATION_PRIORITY, "wfa_wmm_thread",
                           wfa_wmm_thread, 4096, &tdata[i]);
#else
        rtos_create_thread(&wmm_thr[i].thr, TG_APPLICATION_PRIORITY, "wfa_wmm_thread",
                           wfa_wmm_thread, 4096, &tdata[i]);
#endif
        wmm_thr[i].prio = TG_APPLICATION_PRIORITY;
#endif
    }

    for (i = 0; i < WFA_MAX_TRAFFIC_STREAMS; i++)
        tgSockfds[i] = -1;
    // @RW: End

    respBuf = (BYTE *)os_malloc(MAX_UDP_LEN + 1); /* alloc a traffic buffer */
    if (respBuf == NULL) {
        DPRINT_ERR("Failed to malloc traffic buffer\r\n");
        return;
    }

    tmsockfd = wfaCreateTCPServSock(myport);

    maxfdn1 = tmsockfd + 1;

    FD_ZERO(&sockSet);
#if 0
    if(gSock == -1)
    {
        if ((gSock = socket(PF_INET, SOCK_STREAM, IPPROTO_TCP)) < 0)
        {
            DPRINT_ERR("socket() failed: %i", errno);
            exit(1);
        }

        memset(&servAddr, 0, sizeof(servAddr));
        servAddr.sin_family      = AF_INET;
        servAddr.sin_addr.s_addr = inet_addr(servIP);
        servAddr.sin_port        = htons(servPort);

        if (connect(gSock, (struct sockaddr *) &servAddr, sizeof(servAddr)) < 0)
        {
            DPRINT_ERR("connect() failed: %i", errno);
            exit(1);
        }

    }
#endif

    for (;;) {
        FD_ZERO(&sockSet);
        FD_SET(tmsockfd, &sockSet);
        maxfdn1 = tmsockfd + 1;

        if(gCaSockfd != -1)
        {
            FD_SET(gCaSockfd, &sockSet);
            if(maxfdn1 < gCaSockfd + 1)
                maxfdn1 = gCaSockfd +1;
        }
        //os_printf("XXX: tmsockfd %d, gCaSockfd %d, maxfdn1 %d\n", tmsockfd, gCaSockfd, maxfdn1);

#if 0
        if(gSock != -1)
        {
            FD_SET(gSock, &sockSet);
            if(maxfdn1 < gSock)
            maxfdn1 = gSock +1;
        }
#endif

        if((nfds = select(maxfdn1, &sockSet, NULL, NULL, NULL)) < 0)
        {
            //if(errno == EINTR)
            //{
                // DPRINT_WARNING(".");
                continue;
            //}
            //else
            //{
                DPRINT_WARNING("select error %i", errno);
            //}
        }

        DPRINT_INFO("new event \r\n");
        if(FD_ISSET(tmsockfd, &sockSet))
        {
            gCaSockfd = wfaAcceptTCPConn(tmsockfd);
            DPRINT_INFO("accept new connection, gCaSockfd %d\r\n", gCaSockfd);
            continue;
        }

        if(gCaSockfd > 0 && FD_ISSET(gCaSockfd, &sockSet))
        {
            memset(xcCmdBuf, 0, WFA_BUFF_4K);
            memset(gRespStr, 0, WFA_BUFF_512);

            nbytes = wfaCtrlRecv(gCaSockfd, xcCmdBuf);
            if(nbytes <=0)
            {
                shutdown(gCaSockfd, SHUT_WR);
                close(gCaSockfd);
                gCaSockfd = -1;
                continue;
            }
            /*
             * send back to command line or TM.
             */
            //sleep(1); /* having this is for slowing down unexpected output result on CLI command sometimes */
            memset(respStr, 0, WFA_BUFF_128);
            sprintf(respStr, "status,RUNNING\r\n");
            wfaCtrlSend(gCaSockfd, (BYTE *)respStr, strlen(respStr));

            DPRINT_INFO("%s\r\n", respStr);
            DPRINT_INFO("message %s %i\r\n", xcCmdBuf, nbytes);
            slen = (int)strlen((char *)xcCmdBuf);

            //DPRINT_INFO("last %x last-1  %x last-2 %x last-3 %x\r\n", cmdName[slen], cmdName[slen-1], cmdName[slen-2], cmdName[slen-3]);
            DPRINT_INFO("last %x last-1  %x last-2 %x last-3 %x\r\n", xcCmdBuf[slen], xcCmdBuf[slen - 1], xcCmdBuf[slen - 2], xcCmdBuf[slen - 3]);

            xcCmdBuf[slen - 2] = '\0';

            //print_hex_dump("CMD", xcCmdBuf, strlen((char *)xcCmdBuf));

            DPRINT_INFO("XXX: cmd |%s|\r\n", xcCmdBuf);

#if 0
            if(gSock == -1)
            {
                if ((gSock = socket(PF_INET, SOCK_STREAM, IPPROTO_TCP)) < 0)
                {
                    DPRINT_ERR("socket() failed: %i", errno);
                    exit(1);
                }

                memset(&servAddr, 0, sizeof(servAddr));
                servAddr.sin_family      = AF_INET;
                servAddr.sin_addr.s_addr = inet_addr(servIP);
                servAddr.sin_port        = htons(servPort);

                if (connect(gSock, (struct sockaddr *) &servAddr, sizeof(servAddr)) < 0)
                {
                    DPRINT_ERR("connect() failed: %i", errno);
                    exit(1);
                }
            }
#endif

            isFound = 0;

            memcpy(cmdName, strtok_r((char *)xcCmdBuf, ",", (char **)&pcmdStr), 32);

            i = 0;
            // os_printf("cmdName: <<<%s>>>\n", cmdName);
            while (nameStr[i].type != -1) {
                if (strcmp(nameStr[i].name, cmdName) == 0) {
                    isFound = 1;
                    break;
                }
                i++;
            }
            DPRINT_INFO("%s\r\n", cmdName);

            if (isFound == 0) {
                sleep(1);
                sprintf(respStr, "status,INVALID\r\n");
                wfaCtrlSend(gCaSockfd, (BYTE *)respStr, strlen(respStr));
                DPRINT_WARNING("Command not valid, check the name\r\n");
                continue;
            }

            // Convert command string to c structure
            memset(pcmdBuf, 0, WFA_BUFF_1K);
            cmdLen = WFA_BUFF_1K;    // reset to cmdLen to bufsize
            if (nameStr[i].cmdProcFunc(pcmdStr, pcmdBuf, &cmdLen) == WFA_FAILURE) {
                sleep(1);
                sprintf(respStr, "status,INVALID\r\n");
                wfaCtrlSend(gCaSockfd, (BYTE *)respStr, strlen(respStr));
                DPRINT_WARNING("Incorrect command syntax\r\n");
                continue;
            }

            //@RW: Start

            //gGenericResp = (dutCmdResponse_t*)malloc(sizeof(dutCmdResponse_t));
            memset(parmsVal, 0, WFA_BUFF_1K);
            memset(&gGenericResp, 0, sizeof(dutCmdResponse_t));
            memset(respBuf, 0, WFA_RESP_BUF_SZ);
            wfaDecodeTLV(pcmdBuf, cmdLen, &xcCmdTag, &cmdLen1, parmsVal);
            DPRINT_WARNING("tag wfa_cs = %d\r\n", xcCmdTag);


            // xcCmdTag: command tag, cmdLen1: command (struct) len, paramsVal: command (struct format)
            if (xcCmdTag != 0 && gWfaCmdFuncTbl[xcCmdTag] != NULL) {
                // since the new commands are expanded to new block
                gWfaCmdFuncTbl[xcCmdTag](cmdLen1, parmsVal, &respLen, (BYTE *)respBuf);
            } else {
                // no command defined
                NotDefinedYet(cmdLen, parmsVal, &respLen, (BYTE *)respBuf);
            }

            DPRINT_WARNING("respBuf len = %d\r\n", ((wfaTLV *)respBuf)->len);
            DPRINT_WARNING("respBuf tag = %d\r\n", ((wfaTLV *)respBuf)->tag);
            tag = ((wfaTLV *)respBuf)->tag;

            if (tag == WFA_INVALID_TLV)
                printf("No response sent\n");
            else if (tag != 0 && wfaCmdRespProcFuncTbl[tag] != NULL)
                wfaCmdRespProcFuncTbl[tag](respBuf);
            else {
                DPRINT_WARNING("tag shall != 0 --> tag = %d\r\n", tag);
                DPRINT_WARNING("Function not defined\r\n");
                caCmdNotDefinedYet(respBuf);
            }
        }
    }
    //@RW: End

#if 0
    close(gSock);
#endif
    DPRINT_OUT_FUNC();
}

beken_thread_t wfa_ca_thr = 0;

void wfa_ca_start()
{
    bk_err_t ret;

    ret = rtos_create_thread(&wfa_ca_thr, TG_APPLICATION_PRIORITY, "wfa_ca",
                             wfa_ca_main, 4096, NULL);
    if (ret != kNoErr) {
        os_printf("wfa_ca_start: create thread failed %d\r\n", ret);
    }
}

void wfa_ca_stop()
{
    if (wfa_ca_thr) {
        rtos_delete_thread(wfa_ca_thr);
        wfa_ca_thr = 0;
    }
}

void wfa_ca_set(int argc, char **argv)
{
    // os_printf("argc: %d, argv[0] %s\n", argc, argv[0]);
    if (!os_strcmp(argv[0], "clear")) {
        wmm_fc_init();
    } else if (!os_strcmp(argv[0], "dump")) {
        wmm_fc_dump();
    } else if (!os_strcmp(argv[0], "step")) {
        if (argc >= 2)
            wmm_fc_set_step(atoi(argv[1]));
    } else if (!os_strcmp(argv[0], "delay")) {
        if (argc >= 2)
            wmm_fc_set_delay(atoi(argv[1]));
    } else if (!os_strcmp(argv[0], "debug")) {
        if (argc >= 2)
            wmm_fc_set_debug(!!atoi(argv[1]));
    } else {
        /*
         *  Step   TX    AC   PER
         */
        if (argc >= 4) {
            int step = atoi(argv[0]);
            int tx = atoi(argv[1]);
            int ac = atoi(argv[2]);
            int per = atoi(argv[3]);
            wmm_fc_set(step, tx, ac, per);
        }
    }

}


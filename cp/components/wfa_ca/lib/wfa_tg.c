struct wmm_fc *find_wmm_fc(int ac, int tx, int debug)
{
    struct wmm_fc *fc;

    if (wmm_fc_step >= MAX_STEPS || ac >= WMMAC_AC_MAX) {
        if (debug) {
            printf("%s %d: %s\n", __func__, __LINE__, tx ? "tx" : "rx");
        }
        return NULL;
    }

    if (tx)
        fc = &wmm_fc_tx[wmm_fc_step][ac];
    else
        fc = &wmm_fc_rx[wmm_fc_step][ac];

    if (fc->enabled)
        return fc;

    if (debug) {
        printf("%s %d: %s\n", __func__, __LINE__, tx ? "tx" : "rx");
    }
    return NULL;
}

/*
 * wfaTGSetPrio(): This depends on the network interface card.
 *               So you might want to remap according to the driver
 *               provided.
 *               The current implementation is to set the TOS/DSCP bits
 *               in the IP header
 */
int wmm_tos_to_ac(int tos)
{
    int ac;

    switch (tos)
    {
    case TOS_BE:
        ac = WMMAC_AC_BE;   // user priority "0"
        break;

    case TOS_BK:
        ac = WMMAC_AC_BK;
        break;

    case TOS_VI:
        ac = WMMAC_AC_VI;   // user priority "5"
        break;

    case TOS_VO:
        ac = WMMAC_AC_VO;   // user priority "6"
        break;

    default:
        printf("unknown tos\n");
        ac = -1;
        /* default */
        ;
    }
    return ac;
}


// 1: drop packet
int wmm_fc_handle_rx(tgProfile_t *theProf, int tos)
{
    int ac = wmm_tos_to_ac(tos);
    //printf("tos %d, ac %d\n", tos, ac);

    if (ac < 0 || ac > WMMAC_AC_MAX)
        return 0;

    struct wmm_fc *fc = find_wmm_fc(ac, 0, 0);

    if (!fc)
        return 0;

    fc->count++;
    if ((fc->count % 10) < fc->per) {
        // drop packet
        if (wmm_fc_debug)
            printf("%s: drop pkt\n", __func__);
        return 1;
    }

    return 0;
}

// add delay for tx frames
void wmm_fc_handle_tx(tgProfile_t *theProf)
{
    struct wmm_fc *fc = find_wmm_fc(theProf->trafficClass - 1, 1, 0);
    if (!fc) {
        //printf("%s: ac %d, wmm_fc_step %d\n", __func__, theProf->trafficClass - 1, wmm_fc_step);
        return;
    }

    fc->count++;

    if ((fc->count % 10) < fc->per) {
        // delay tx
        if (wmm_fc_debug)
            printf("%s: delay %d for ac %d\n", __func__, wmm_fc_delay, theProf->trafficClass  - 1);
        wUSLEEP(wmm_fc_delay);
    }
}

/**
 ****************************************************************************************
 * @brief Verify if string contains ip address
 * @return 0 if string contained what looks like a valid ip address and -1 otherwise
 ****************************************************************************************
 */
int IsIp4(char *str)
{
    char *token = NULL;
    // store part of ip address (between dots)
    char tmp[4];
    // length of part of ip address (1 ~ 3)
    int len;
    uint32_t a, i, j;

    // parse the ip part
    for (i = 0; i < 4; i ++) {
        if (i < 3) {
            token = strchr(str, '.');
            if (!token)
                return -1;

            len = token - str;
        } else {
            // if it's the last part of ip address
            len = strlen(str);
        }
        check_is_num(str, len);
        // retrieve number between dot
        memset(tmp, 0, 4);
        strncpy(tmp, str, len);

        a = atoi(tmp);
        if (a > 255)
            return -1;
        str = ++token;
    }

    return 0;
}


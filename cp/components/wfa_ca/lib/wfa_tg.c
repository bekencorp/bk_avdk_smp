/*
 * findStreamProfile(): search existing stream profile by stream id
 * input: id - stream id;
 * return: matched stream profile
 */
tgStream_t *findStreamProfile(int id)
{
    int i;
    tgStream_t *myStream = gStreams;

    for (i = 0; i < WFA_MAX_TRAFFIC_STREAMS; i++) {
        if (myStream->id == id)
            return myStream;

        myStream++;
    }

    return NULL;
}


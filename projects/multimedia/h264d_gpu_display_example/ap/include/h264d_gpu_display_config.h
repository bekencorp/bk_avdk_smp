#endif
#ifndef CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_WIDTH
/*
 * ISP outputs NV12 for the PIP path. Keep width on a 16-pixel
 * boundary for GPU/DMA-friendly stride alignment, and keep width/height
 * even because NV12 is 4:2:0.
 *
 * Default 640x360 = half of 1280x720 (sensor input), so the ISP
 * channel does an exact 2x2 down-scale without distortion or extra
 * filtering complexity.
 */
#define CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_WIDTH       640
#endif
#ifndef CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_HEIGHT
#define CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_HEIGHT      360
#endif
#ifndef CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_DST_X
#if H264D_GPU_DISPLAY_ENABLE_ISP_PIP_ROTATE
/*
 * 1088 - 360 - 32 = 696 -> right-anchored rotated PIP with a 32 px
 * margin on a 1088x1920 portrait panel. The default ISP output is
 * 640x360, but it is visibly 360x640 after 90/270-degree blit rotation.
 */
#define CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_DST_X       696
#else
/*
 * 1088 - 640 - 32 = 416 -> right-anchored PIP with a 32 px margin on a
 * 1088x1920 portrait panel, mirroring the WeChat self-view layout.
 */
#define CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_DST_X       416
#endif
#endif
#ifndef CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_DST_Y
#define CONFIG_H264D_GPU_DISPLAY_ISP_PIP_DEFAULT_DST_Y       32
#endif


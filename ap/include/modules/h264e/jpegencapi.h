  u32 olEnable[MAX_OVERLAY_NUM];
  /** \brief The input formats of each OSD area.
    *\n <tt>0</tt>: ARGB8888.
    *\n <tt>1</tt>: NV12.
    *\n <tt>2</tt>: Bitmap. */

#!/usr/bin/env python3
"""Convert JavaScript sources into C string literals.

This is a project independent helper for the bk_jerryscript component: it turns
one or more .js files into a C array that can be compiled into the firmware and
passed to bk_js_eval().  It has no dependency on JerryScript build scripts and
makes no assumption about the project layout.

Typical use:

    # one script -> header holding a static array
    python3 js2c.py ui.js -o ui_js.h

    # several scripts merged in the given order -> .c plus header
    python3 js2c.py a.js b.js c.js -o js_bundle.c --header js_bundle.h

    # every .js under a directory, recursively
    python3 js2c.py ap/js -o js_bundle.c --header js_bundle.h --recursive

The generated accessors are:

    const char *<name>_source(void);   /* NUL terminated source */
    unsigned int <name>_len(void);     /* length in bytes, excluding NUL */

Byte escaping uses fixed width octal escapes.  Hex escapes (\\xNN) are avoided
on purpose: in C they consume as many hex digits as possible, so a value such
as 0x01 followed by the character '0' would silently be read as 0x10.
"""

import argparse
import glob
import os
import re
import sys

DEFAULT_CHUNK = 100


def escape_tokens(data):
    """Return C string literal tokens for a byte string."""
    tokens = []

    for byte in data:
        if byte == 0x22:            # '"'
            tokens.append('\\"')
        elif byte == 0x5C:          # backslash
            tokens.append('\\\\')
        elif byte == 0x3F:          # '?', keeps trigraphs out
            tokens.append('\\?')
        elif byte == 0x0A:
            tokens.append('\\n')
        elif byte == 0x0D:
            tokens.append('\\r')
        elif byte == 0x09:
            tokens.append('\\t')
        elif 0x20 <= byte < 0x7F:
            tokens.append(chr(byte))
        else:
            # Fixed width octal: a following digit can never be absorbed.
            tokens.append('\\%03o' % byte)

    return tokens


def emit_literal(data, indent, chunk):
    """Split data into C string literal lines, one per source line."""
    lines = []
    parts = data.split(b'\n')

    for index, part in enumerate(parts):
        if index < len(parts) - 1:
            part += b'\n'

        if not part:
            continue

        current = ''
        for token in escape_tokens(part):
            if current and len(current) + len(token) > chunk:
                lines.append('%s"%s"' % (indent, current))
                current = ''
            current += token

        if current:
            lines.append('%s"%s"' % (indent, current))

    if not lines:
        lines.append('%s""' % indent)

    return lines


def sanitize(name):
    out = re.sub(r'[^0-9A-Za-z_]', '_', name)
    if not out or out[0].isdigit():
        out = '_' + out
    return out


def guard_name(path):
    return '_' + sanitize(os.path.basename(path)).upper() + '_INCLUDED'


def collect_files(paths, recursive):
    """Expand files and directories into an ordered list of .js paths."""
    files = []

    for path in paths:
        if os.path.isdir(path):
            pattern = '**/*.js' if recursive else '*.js'
            found = glob.glob(os.path.join(path, pattern),
                              recursive=recursive)
            found = sorted(p for p in found if os.path.isfile(p))
            if not found:
                sys.exit('js2c: no .js files under %s' % path)
            files.extend(found)
        elif os.path.isfile(path):
            files.append(path)
        else:
            sys.exit('js2c: no such file or directory: %s' % path)

    if not files:
        sys.exit('js2c: no input files')

    return files


def read_sources(files, separator, crlf):
    """Concatenate the sources, optionally tagging each one with a comment."""
    chunks = []

    for path in files:
        with open(path, 'rb') as fp:
            data = fp.read()

        if crlf:
            data = data.replace(b'\r\n', b'\n')

        if separator:
            tag = path.replace(os.sep, '/')
            chunks.append(b'/* ---- ' + tag.encode('utf-8', 'replace')
                          + b' ---- */\n')

        chunks.append(data)

        if data and not data.endswith(b'\n'):
            chunks.append(b'\n')

    return b''.join(chunks)


def build_header(path, name, var, data, chunk):
    """Build a header file.

    When data is None the header only declares the accessors implemented by a
    matching .c file.  Otherwise the array is defined inline as static, which
    lets a single include carry the whole script.
    """
    guard = guard_name(path)
    out = [
        '/*',
        ' * Generated by js2c.py - do not edit.',
        ' */',
        '#ifndef %s' % guard,
        '#define %s' % guard,
        '',
    ]

    if data is None:
        out.extend([
            '#ifdef __cplusplus',
            'extern "C" {',
            '#endif',
            '',
            '/* NUL terminated JavaScript source. */',
            'const char *%s_source(void);' % name,
            '',
            '/* Length in bytes, excluding the trailing NUL. */',
            'unsigned int %s_len(void);' % name,
            '',
            '#ifdef __cplusplus',
            '}',
            '#endif',
            '',
        ])
    else:
        out.extend([
            '/* Inline array: include this header where the script is used. */',
            'static const char %s[] =' % var,
        ])
        out.extend(emit_literal(data, '\t', chunk))
        out.append('\t;')
        out.append('')

    out.append('#endif /* %s */' % guard)
    out.append('')

    return '\n'.join(out)


def build_source(name, var, static, array_only, header, data, files, chunk):
    storage = 'static ' if static else ''
    out = [
        '/*',
        ' * Generated by js2c.py - do not edit.',
        ' * %d input file(s), %d bytes.' % (len(files), len(data)),
        ' */',
    ]

    if header:
        out.append('#include "%s"' % os.path.basename(header))

    out.append('')
    out.append('%sconst char %s[] =' % (storage, var))
    out.extend(emit_literal(data, '\t', chunk))
    out.append('\t;')
    out.append('')

    if not array_only:
        out.extend([
            '%sconst char *%s_source(void)' % (storage, name),
            '{',
            '\treturn %s;' % var,
            '}',
            '',
            '%sunsigned int %s_len(void)' % (storage, name),
            '{',
            '\treturn (unsigned int)(sizeof(%s) - 1u);' % var,
            '}',
            '',
        ])

    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(
        description='Convert JavaScript sources into a C string constant.')
    parser.add_argument('inputs', nargs='+',
                        help='.js files and/or directories, in merge order')
    parser.add_argument('-o', '--output', required=True,
                        help='output .c or .h file')
    parser.add_argument('--header',
                        help='also write this .h next to the .c output')
    parser.add_argument('--name',
                        help='symbol prefix (default: output file stem)')
    parser.add_argument('--var',
                        help='array name (default: s_<name>)')
    parser.add_argument('--array-only', action='store_true',
                        help='emit the array only, without accessor functions')
    parser.add_argument('--static', action='store_true',
                        help='make the array and functions static')
    parser.add_argument('--recursive', action='store_true',
                        help='walk directories recursively')
    parser.add_argument('--separator', dest='separator', action='store_true',
                        help='insert a /* ---- file ---- */ comment before '
                             'each input (off by default, so the generated '
                             'string is the exact concatenation)')
    parser.add_argument('--no-separator', dest='separator',
                        action='store_false',
                        help='merge the sources without comment tags')
    parser.set_defaults(separator=None)
    parser.add_argument('--crlf', action='store_true',
                        help='convert CRLF line endings to LF')
    parser.add_argument('--chunk', type=int, default=DEFAULT_CHUNK,
                        help='max characters per literal line (default: %d)'
                             % DEFAULT_CHUNK)
    args = parser.parse_args()

    out_path = args.output
    if not out_path.lower().endswith(('.c', '.h')):
        parser.error('output must end with .c or .h')

    is_header = out_path.lower().endswith('.h')
    if is_header and args.header:
        parser.error('--header is only valid with a .c output')
    if args.static and args.header:
        parser.error('--static makes the accessors private, drop --header')

    files = collect_files(args.inputs, args.recursive)

    separator = bool(args.separator)
    data = read_sources(files, separator, args.crlf)

    stem = os.path.splitext(os.path.basename(out_path))[0]
    name = args.name or stem
    if not re.match(r'^[A-Za-z_][0-9A-Za-z_]*$', name):
        parser.error('invalid C identifier for --name: %s' % name)

    var = args.var or 's_' + sanitize(stem)
    if not re.match(r'^[A-Za-z_][0-9A-Za-z_]*$', var):
        parser.error('invalid C identifier for --var: %s' % var)

    if is_header:
        if args.array_only:
            parser.error('--array-only needs a .c output')
        text = build_header(out_path, name, var, data, args.chunk)
    else:
        text = build_source(name, var, args.static, args.array_only,
                            args.header, data, files, args.chunk)

    parent = os.path.dirname(os.path.abspath(out_path))
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)

    with open(out_path, 'w', encoding='ascii', newline='\n') as fp:
        fp.write(text)

    if args.header:
        header_text = build_header(args.header, name, var, None, args.chunk)
        with open(args.header, 'w', encoding='ascii', newline='\n') as fp:
            fp.write(header_text)

    print('js2c: %d file(s), %d bytes -> %s (%s)'
          % (len(files), len(data), out_path, var))


if __name__ == '__main__':
    main()

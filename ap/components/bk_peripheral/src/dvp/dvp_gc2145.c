avdk_err_t gc2145_set_ppi(bk_camera_sensor_ctlr_t *controller, uint16_t width, uint16_t height)
{
    uint32_t size, i;
    int ret = -1;

    LOGI("%s\n", __func__);

    bk_camera_dvp_sensor_t *dvp_sensor = __containerof(controller, bk_camera_dvp_sensor_t, ops);
    AVDK_RETURN_ON_FALSE(dvp_sensor, AVDK_ERR_INVAL, TAG, "dvp sensor is NULL");
    bk_camera_bus_t *bus = dvp_sensor->config.bus;

    if (width == 480 && height == 480)
    {
        size = sizeof(sensor_gc2145_480_480_table) / 2;

        for (i = 0; i < size; i++)
        {
            bus->write8(bus, sensor_gc2145_480_480_table[i][0], sensor_gc2145_480_480_table[i][1]);
        }
        ret = 0;
    }
    else if (width == 640 && height == 480)
    {
        size = sizeof(sensor_gc2145_640_480_table) / 2;

            for (i = 0; i < size; i++)
            {
                bus->write8(bus, sensor_gc2145_640_480_table[i][0], sensor_gc2145_640_480_table[i][1]);
            }
            ret = 0;
    }
    else if (width == 1280 && height == 720)
    {
            size = sizeof(sensor_gc2145_1280_720_table) / 2;

            for (i = 0; i < size; i++)
            {
                bus->write8(bus, sensor_gc2145_1280_720_table[i][0], sensor_gc2145_1280_720_table[i][1]);
            }
            ret = 0;
    }
    else
    {
        LOGI("not supported width: %d, height: %d\r\n", width, height);
        ret = -1;
    }

    return ret;
}


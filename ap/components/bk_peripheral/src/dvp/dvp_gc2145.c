avdk_err_t gc2145_init(bk_camera_sensor_ctlr_t *controller)
{
    bk_dvp_io_config();

    bk_mipi_csi_ext_set_enable(1);

    bk_camera_dvp_sensor_t *dvp_sensor = __containerof(controller, bk_camera_dvp_sensor_t, ops);
    AVDK_RETURN_ON_FALSE(dvp_sensor, AVDK_ERR_INVAL, TAG, "dvp sensor is NULL");
    bk_camera_bus_t *bus = dvp_sensor->config.bus;
    uint32_t size = sizeof(sensor_gc2145_init_talbe) / 2, i;

    LOGI("%s start\n", __func__);

    for (i = 0; i < size; i++)
    {
        bus->write8(bus, sensor_gc2145_init_talbe[i][0], sensor_gc2145_init_talbe[i][1]);
    }

    return 0;
}


avdk_err_t gc2145_set_fps(bk_camera_sensor_ctlr_t *controller, uint16_t fps)
{
    int ret = 0, size = 0, i = 0;
    uint8_t width_h, width_l = 0;
    uint16_t width = 0;

    bk_camera_dvp_sensor_t *dvp_sensor = __containerof(controller, bk_camera_dvp_sensor_t, ops);
    AVDK_RETURN_ON_FALSE(dvp_sensor, AVDK_ERR_INVAL, TAG, "dvp sensor is NULL");
    bk_camera_bus_t *bus = dvp_sensor->config.bus;

    bus->read8(bus, 0x97, &width_h);
    bus->read8(bus, 0x98, &width_l);

    width = width_h << 8 | width_l;

    if (width == 0x0500) // 1280*720
    {
        switch (fps)
        {
            case 20:
            {
                size = sizeof(sensor_gc2145_1280_720_20fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_1280_720_20fps_table[i][0], sensor_gc2145_1280_720_20fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            case 15:
            {
                size = sizeof(sensor_gc2145_1280_720_15fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_1280_720_15fps_table[i][0], sensor_gc2145_1280_720_15fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            case 10:
            {
                size = sizeof(sensor_gc2145_1280_720_10fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_1280_720_10fps_table[i][0], sensor_gc2145_1280_720_10fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            default:
            {
                size = sizeof(sensor_gc2145_1280_720_20fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_1280_720_20fps_table[i][0], sensor_gc2145_1280_720_20fps_table[i][1]);
                }

                ret = 0;
                break;
            }

        }
    }

    if (width == 0x0280) // 640*480
    {
        switch (fps)
        {
            case 30:
            {
                size = sizeof(sensor_gc2145_640_480_30fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_640_480_30fps_table[i][0], sensor_gc2145_640_480_30fps_table[i][1]);
                }

                ret = 0;
                break;
            }


            case 25:
            {
                size = sizeof(sensor_gc2145_640_480_25fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_640_480_25fps_table[i][0], sensor_gc2145_640_480_25fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            case 20:
            {
                size = sizeof(sensor_gc2145_640_480_20fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_640_480_20fps_table[i][0], sensor_gc2145_640_480_20fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            case 15:
            {
                size = sizeof(sensor_gc2145_640_480_15fps_table) / 2;

                for (i = 0; i < size; i++)
                {
                    bus->write8(bus, sensor_gc2145_640_480_15fps_table[i][0], sensor_gc2145_640_480_15fps_table[i][1]);
                }

                ret = 0;
                break;
            }

            default:
                ret = 0;
                break;
        }
    }

    return ret;
}


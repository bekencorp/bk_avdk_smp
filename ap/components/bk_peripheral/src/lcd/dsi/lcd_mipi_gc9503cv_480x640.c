static const uint8_t gc9503cv_mipi_480x640_read_id_regs[] = {0x04, 0};

const bk_display_dsi_panel_t lcd_device_gc9503cv_mipi_480x640 = {
    .id = 0x9503,
    .name = "gc9503cv_mipi_480x640",
    .n_lanes = DSI_ACTIVE_LANES_1,
    /* The panel is rated for 500 Mbps on its single data lane. There is no
     * PLL ratio that satisfies 1-lane/24bpp, so the DPU falls back to SYSCLK
     * and hal_dsi_sysclk_lane_mbps_select() sizes the lane from the pixel
     * clock. 32 fps (pclk 12.2 MHz over 550x694 total) lands on the 500 Mbps
     * bracket; raising fps picks 600/700/800 and the link visibly corrupts. */
    .fps = 32,
    .timing = {
        .h_size = PIXEL_480,
        .v_size = PIXEL_640,
        .hsync_pulse_width = 10,
        .vsync_pulse_width = 8,
        .hsync_back_porch = 30,
        .hsync_front_porch = 30,
        .vsync_back_porch = 34,
        .vsync_front_porch = 12,
    },
    .init_cmds = gc9503cv_mipi_480x640_init_cmds,
    .off_cmds = gc9503cv_mipi_480x640_off_cmds,
    .read_id_regs = gc9503cv_mipi_480x640_read_id_regs,
    .read_id_bytes = 3,
    .reset_active_level = false,
    .reset = bk_lcd_mipi_default_reset,
    .init = bk_lcd_mipi_default_init,
    .off = bk_lcd_mipi_default_off,
};


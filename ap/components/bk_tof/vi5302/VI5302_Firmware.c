uint8_t Get_VI5302_Download_Firmware_Status(void)
{
    uint8_t value;
    uint8_t ret = 0;

    ret |= VI5302_IIC_Read_One_Byte(0x08, &value);

    if (0x66 == value && ret == 0)
    {
        return 0;
    }
    else
    {
        return 1;
    }
}

uint8_t VI5302_Write_Firmware_PreConfig(void)
{
    uint8_t ret = 0;
    uint8_t reg_sys_cfg = 0;

    ret |= VI5302_IIC_Write_One_Byte(REG_PW_CTRL, 0x30);
    ret |= VI5302_IIC_Write_One_Byte(REG_MCU_CFG, 0x36);
    ret |= VI5302_IIC_Read_One_Byte(REG_SYS_CFG, &reg_sys_cfg);
    ret |= VI5302_IIC_Write_One_Byte(REG_SYS_CFG, reg_sys_cfg | (0x01 << 0));    
    ret |= VI5302_IIC_Write_One_Byte(REG_CMD, 0x01);
    ret |= VI5302_IIC_Write_One_Byte(REG_SIZE, 0x02);
    ret |= VI5302_IIC_Write_One_Byte(REG_SCRATCH_PAD_BASE + 0x00, 0x00);
    ret |= VI5302_IIC_Write_One_Byte(REG_SCRATCH_PAD_BASE + 0x01, 0x00);

    return ret;
}


uint8_t VI5302_Write_Firmware_Post_Config(void)
{
    uint8_t ret = 0;

    ret |= VI5302_IIC_Write_One_Byte(REG_SYS_CFG, 0x0c);
    ret |= VI5302_IIC_Write_One_Byte(REG_DTOP_3, 0xA0);
    ret |= VI5302_IIC_Write_One_Byte(REG_DTOP_3, 0x80);
    ret |= VI5302_IIC_Write_One_Byte(REG_SPECIAL_PURP1, 0x00);
    ret |= VI5302_IIC_Write_One_Byte(REG_MCU_CFG, 0x16);
    ret |= VI5302_IIC_Write_One_Byte(REG_MCU_CFG, 0x17);

    return ret;
}

uint8_t VI5302_Download_Firmware(uint8_t *Firmware_buff, uint16_t size)
{
    uint8_t ret = 0;
    uint8_t page = 0;
    uint8_t temp_buff[2];
    uint8_t ma_buff[9] = {0};

    ret |= VI5302_Write_Firmware_PreConfig();
    while (size >= 64)
    {
        temp_buff[0] = CMD_WRITEFW;
        temp_buff[1] = 64;

        ret |= VI5302_IIC_Write_X_Bytes(REG_CMD, temp_buff, 2);
        ret |= VI5302_IIC_Write_X_Bytes(REG_SCRATCH_PAD_BASE, Firmware_buff + page * 64, 64);
        VI5302_Delay_Ms(1);
        size -= 64;
        page++;
        if(ret)
        {
            return ret;
        }
    }
    if (size > 0)
    {
        temp_buff[0] = CMD_WRITEFW;
        temp_buff[1] = size;

        ret |= VI5302_IIC_Write_X_Bytes(REG_CMD, temp_buff, 2);
        ret |= VI5302_IIC_Write_X_Bytes(REG_SCRATCH_PAD_BASE, Firmware_buff + page * 64, size);
    }
    ret |= VI5302_Write_Firmware_Post_Config();

    VI5302_Delay_Ms(50);
    ret |= Get_VI5302_Download_Firmware_Status();

    ret |= VI5302_Get_Sys_Histogram_MA_Window_Data(ma_buff);
    VI5302_Cali_Data.VI5302_MA_Sum = ma_buff[8];

    return ret;
}

